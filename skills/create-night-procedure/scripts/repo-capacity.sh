#!/usr/bin/env bash
# What a repository can absorb, so a night-run target is chosen with the facts.
# Usage: repo-capacity.sh <owner>/<repo> <your-github-login>
# Prints outside PRs merged in the last 30 days, median days to merge for them,
# your open PRs there, open issues under common good-issue labels, and every
# policy line about AI, agents, LLMs, or generated code.
set -euo pipefail
[ $# -eq 2 ] || { echo "usage: $0 <owner>/<repo> <login>" >&2; exit 2; }
repo="$1" login="$2"
since="$(date -d '30 days ago' +%F)"

merged="$(gh search prs --repo "$repo" --merged --merged-at ">=$since" --limit 1000 \
  --json author,authorAssociation,createdAt,closedAt)"
outside="$(jq '[.[] | select(.author.type != "Bot" and (.author.login | endswith("[bot]") | not))
  | select(.authorAssociation | IN("CONTRIBUTOR","FIRST_TIME_CONTRIBUTOR","FIRST_TIMER","NONE"))]' <<<"$merged")"

echo "repository: $repo"
echo "merged PRs since $since: $(jq length <<<"$merged") total, $(jq length <<<"$outside") from outside contributors"
echo "median days to merge (outside): $(jq -r '
  [.[] | ((.closedAt | fromdateiso8601) - (.createdAt | fromdateiso8601)) / 86400] | sort
  | if length == 0 then "n/a"
    elif length % 2 == 1 then .[(length / 2 | floor)] * 10 | round / 10
    else (.[length / 2 - 1] + .[length / 2]) / 2 * 10 | round / 10 end' <<<"$outside")"
echo "your open PRs: $(gh pr list -R "$repo" --author "$login" --state open --limit 1000 --json number --jq length)"

for label in "good first issue" "help wanted" "agent/ready"; do
  n="$(gh issue list -R "$repo" --state open --label "$label" --limit 500 --json number --jq length 2>/dev/null || echo 0)"
  [ "$n" = 0 ] || echo "open issues labelled '$label': $n"
done

echo "policy lines mentioning AI, agents, LLMs, or generated code:"
found=0
for path in CONTRIBUTING.md .github/CONTRIBUTING.md docs/CONTRIBUTING.md .github/PULL_REQUEST_TEMPLATE.md AGENTS.md CLAUDE.md; do
  text="$(gh api "repos/$repo/contents/$path" -H "Accept: application/vnd.github.raw" 2>/dev/null)" || continue
  hits="$(grep -n -i -P '\bAI\b|artificial intelligence|\bagents?\b(?!\.md)|\bLLMs?\b|auto-generated|AI-generated|generated by|copilot|chatgpt|claude(?!\.md)' <<<"$text" || true)"
  [ -n "$hits" ] && { found=1; sed "s|^|  $path:|" <<<"$hits"; }
done
[ "$found" = 1 ] || echo "  none found in the usual files; read CONTRIBUTING and the docs before deciding"
